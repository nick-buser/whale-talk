    crossspecies: 'Zipfian rank-frequency distributions have been reported in humpback whale song syllables (Suzuki et al. 2006), vervet alarm calls, and dolphin whistle elements. The distribution follows from any system that communicates efficiently under bandwidth constraints — it is a consequence of optimizing for learnability and transmission efficiency, not a signature of language specifically.',
    cite: 'Zipf (1949); Piantadosi et al. (2014, PNAS); Mandelbrot (1953)',
